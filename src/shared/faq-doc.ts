/**
 * 把 FAQ 正文的 Markdown 还原成纯文本，用于结构化数据。
 * FAQPage 的 acceptedAnswer 需要纯文本，链接标记原样输出会被当成乱码。
 */
export function faqAnswerText(markdown: string): string {
  return markdown
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}
